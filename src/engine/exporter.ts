import { NestingResult, SheetNestLayout } from '../types/fabrication';

/**
 * Generates an annotated, millimeter-accurate SVG Cut Sheet (resolving opcut #36 & SVGnest export gaps).
 */
export function exportSheetToSvg(
  layout: SheetNestLayout,
  kerfMm: number,
  includeAnnotations = true
): string {
  const { sheet, placements, salvageableOffcuts } = layout;
  const outerPoints = sheet.outerPolygon.map((p) => `${p.x},${p.y}`).join(' ');

  const holesSvg = sheet.cutoutHoles
    .map((h) => {
      const pts = h.polygon.map((p) => `${p.x},${p.y}`).join(' ');
      return `  <polygon points="${pts}" fill="#ef4444" fill-opacity="0.15" stroke="#ef4444" stroke-width="0.6" stroke-dasharray="3,2" data-layer="forbidden-cutout" />`;
    })
    .join('\n');

  const partsSvg = placements
    .map((p) => {
      const pts = p.worldPolygon.map((pt) => `${pt.x},${pt.y}`).join(' ');
      const cx = (p.x + p.width / 2).toFixed(1);
      const cy = (p.y + p.height / 2).toFixed(1);
      const label = includeAnnotations
        ? `\n    <text x="${cx}" y="${cy}" font-family="monospace" font-size="8" fill="#111827" text-anchor="middle" dominant-baseline="middle">${escapeXml(p.partName)} (${p.width}x${p.height}mm)</text>`
        : '';
      return `  <g id="${escapeXml(p.instanceId)}" data-part="${escapeXml(p.partName)}" data-rotation="${p.rotationDeg}">
    <polygon points="${pts}" fill="${p.color}" fill-opacity="0.18" stroke="#cc0000" stroke-width="${Math.max(0.2, kerfMm).toFixed(2)}" />${label}
  </g>`;
    })
    .join('\n');

  const offcutsSvg = includeAnnotations
    ? salvageableOffcuts
        .map(
          (o) =>
            `  <rect x="${o.x}" y="${o.y}" width="${o.width}" height="${o.height}" fill="none" stroke="#10b981" stroke-width="0.8" stroke-dasharray="4,3" data-layer="salvageable-remnant" />`
        )
        .join('\n')
    : '';

  return `<?xml version="1.0" encoding="UTF-8"?>
<svg xmlns="http://www.w3.org/2000/svg" width="${sheet.width}mm" height="${sheet.height}mm" viewBox="0 0 ${sheet.width} ${sheet.height}">
  <metadata>Generated by KerfCraft (RemnantNest) | Sheet: ${escapeXml(sheet.name)} | Yield: ${layout.utilizationPct}% | Kerf: ${kerfMm}mm</metadata>
  <polygon points="${outerPoints}" fill="none" stroke="#0284c7" stroke-width="0.8" data-layer="sheet-boundary" />
${holesSvg}
${partsSvg}
${offcutsSvg}
</svg>`;
}

/**
 * Generates a valid AutoCAD R12/2000 ASCII DXF file with closed LWPOLYLINE layers:
 * - SHEET_BORDER (Color 5 Blue)
 * - REMNANT_HOLES (Color 1 Red)
 * - CUT_PATHS (Color 2 Yellow / Laser Vector)
 * - SALVAGE_OFFCUTS (Color 3 Green)
 */
export function exportSheetToDxf(layout: SheetNestLayout): string {
  const lines: string[] = [
    '0',
    'SECTION',
    '2',
    'HEADER',
    '9',
    '$INSUNITS',
    '70',
    '4', // 4 = Millimeters
    '0',
    'ENDSEC',
    '0',
    'SECTION',
    '2',
    'ENTITIES',
  ];

  const appendLwPolyline = (
    layer: string,
    colorCode: number,
    pts: Array<{ x: number; y: number }>
  ) => {
    lines.push(
      '0',
      'LWPOLYLINE',
      '8',
      layer,
      '62',
      String(colorCode),
      '90',
      String(pts.length),
      '70',
      '1' // Closed polyline
    );
    for (const p of pts) {
      lines.push('10', p.x.toFixed(3), '20', p.y.toFixed(3));
    }
  };

  // 1. Sheet boundary
  appendLwPolyline('SHEET_BORDER', 5, layout.sheet.outerPolygon);

  // 2. Remnant cutout holes
  for (const hole of layout.sheet.cutoutHoles) {
    appendLwPolyline('REMNANT_HOLES', 1, hole.polygon);
  }

  // 3. Placed part cut paths
  for (const placement of layout.placements) {
    appendLwPolyline('CUT_PATHS', 2, placement.worldPolygon);
  }

  // 4. Salvageable offcuts
  for (const offcut of layout.salvageableOffcuts) {
    appendLwPolyline('SALVAGE_OFFCUTS', 3, [
      { x: offcut.x, y: offcut.y },
      { x: offcut.x + offcut.width, y: offcut.y },
      { x: offcut.x + offcut.width, y: offcut.y + offcut.height },
      { x: offcut.x, y: offcut.y + offcut.height },
    ]);
  }

  lines.push('0', 'ENDSEC', '0', 'EOF');
  return lines.join('\n');
}

/**
 * Generates a structured Markdown / Shop Cutlist & Waste Audit Report
 */
export function generateShopAuditReport(result: NestingResult, jobTitle: string): string {
  const lines: string[] = [
    `# KerfCraft Shop Cutlist & Waste Reduction Audit`,
    `- **Job**: ${jobTitle} (\`${result.jobId}\`)`,
    `- **Timestamp**: ${result.timestamp}`,
    `- **Blade / Laser Kerf Compensation**: ${result.kerfMm} mm`,
    `- **Minimum Inter-Part Clearance**: ${result.partSpacingMm} mm`,
    `- **Zero-Overlap Verification**: ${result.zeroOverlapVerified ? 'PASSED (0.0 mm² collision)' : 'FAILED'}`,
    `- **Parts Placed**: ${result.totalPartsPlaced} / ${result.totalPartsRequested} (${result.remnantPartsPlaced} rescued on remnant scrap)`,
    `- **Material Yield**: ${result.overallYieldPct}% (vs. ${result.naiveFreshSheetYieldPct}% naive fresh-sheet layout)`,
    `- **Remnant Scrap Area Rescued**: ${result.remnantAreaRescuedCm2} cm²`,
    `- **Total Physical Scrap Reduced**: ${result.scrapReducedCm2} cm²`,
    `- **Estimated Material Cost Saved**: $${result.estimatedCostSavedUsd.toFixed(2)} USD`,
    ``,
    `## Sheet-by-Sheet Placement Schedule`,
  ];

  for (const sl of result.sheetsUsed) {
    if (sl.placements.length === 0) continue;
    lines.push(
      `### ${sl.sheet.name} [${sl.sheet.kind === 'remnant' ? 'RESCUED REMNANT' : 'FRESH STOCK'}] — ${sl.sheet.width}×${sl.sheet.height} mm (${sl.utilizationPct}% Yield)`
    );
    lines.push(`| Part Instance | Origin (X, Y mm) | Bounding Size (mm) | Rotation | Grain Lock |`);
    lines.push(`|---|---|---|---|---|`);
    for (const p of sl.placements) {
      lines.push(
        `| ${p.partName} | (${p.x}, ${p.y}) | ${p.width} × ${p.height} | ${p.rotationDeg}° | ${p.grainLocked ? 'Locked 0°/180°' : 'Free'} |`
      );
    }
    if (sl.salvageableOffcuts.length > 0) {
      lines.push(``);
      lines.push(`**New Salvageable Offcuts to Return to Remnant Bin:**`);
      for (const o of sl.salvageableOffcuts) {
        lines.push(
          `- Offcut \`${o.id}\`: **${o.width} × ${o.height} mm** at (${o.x}, ${o.y}) — ${(o.areaMm2 / 100).toFixed(1)} cm² (~$${o.estimatedValueUsd.toFixed(2)} value)`
        );
      }
    }
    lines.push(``);
  }

  return lines.join('\n');
}

function escapeXml(unsafe: string): string {
  return unsafe.replace(/[<>&'"]/g, (c) => {
    switch (c) {
      case '<':
        return '&lt;';
      case '>':
        return '&gt;';
      case '&':
        return '&amp;';
      case '\'':
        return '&apos;';
      case '"':
        return '&quot;';
      default:
        return c;
    }
  });
}
